#!/usr/bin/env bash
# Export agent prompt / routing MD into RAG mirror for Open WebUI (# brand-ip-knowledge).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MIRROR="${BRAND_KNOWLEDGE_MIRROR:-/Users/danying/Desktop/未命名/LLM-Ollama/RAG/RAG/brand-knowledge-mirror}"
OUT="$MIRROR/_rag/agent-prompt-pack"

mkdir -p "$OUT"

copy() {
  local src="$1"
  local dest="$OUT/$(basename "$src")"
  if [[ -f "$src" ]]; then
    cp "$src" "$dest"
    echo "copied $(basename "$src")"
  fi
}

copy "$ROOT/docs/PROMPT-CONTEXT-STANDARD.md"
copy "$ROOT/docs/COURSE-METHOD-TO-YOUR-STACK.md"
copy "$ROOT/docs/CONTEXT-WINDOW-AND-DATA-ROUTING.md"
copy "$ROOT/docs/OPENWEBUI-INTAKE-PROMPT-TEMPLATE.md"
copy "$ROOT/docs/OPENWEBUI-CEO-ROUTER.md"
copy "$ROOT/integration/handoff/cursor-openwebui-task-routing.json"

for f in "$ROOT"/agents/*/INTEGRATION-PROMPT.md; do
  [[ -f "$f" ]] || continue
  bn="$(basename "$(dirname "$f")")-INTEGRATION-PROMPT.md"
  cp "$f" "$OUT/$bn"
  echo "copied $bn"
done

copy "$ROOT/agents/_shared/COLLECTOR-EVALUATOR.md"

cat > "$OUT/README-agent-prompt-pack.md" <<EOF
# Agent Prompt Pack (auto-export)

Generated by danying-brand-agent/scripts/export-agent-prompt-pack.sh

Purpose: Open WebUI RAG answers **how we route prompts** (Cursor vs Pipe vs RAG).
Does NOT replace Cursor for verify, gate, or code.

Sync: cd LLM-Ollama/RAG/RAG/scripts && python3 sync_brand_drive_to_openwebui.py
Chat: # brand-ip-knowledge — ask about INTEGRATION-PROMPT or PROMPT-CONTEXT-STANDARD
EOF

echo "EXPORT_OK → $OUT ($(ls -1 "$OUT" | wc -l | tr -d ' ') files)"
